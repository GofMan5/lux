// WHY: the overlay upgrades measured widths to Unicode 18.0.0 "one size fits
// most" semantics, but the honest terminal answer is not universal: East
// Asian Ambiguous codepoints take one cell on Western setups and two on
// CJK-locale terminals, some terminals ignore VS16 emoji presentation
// entirely, and a few legacy console stacks still render every emoji in a
// single cell. A WidthPolicy records which of those quirks the target
// terminal has; the render pipeline then applies it uniformly, so drawing and
// measuring always agree.
//
// The zero value is the policy of a modern, Western-locale, Unicode-capable
// terminal and matches the historical behavior of the render package exactly:
// ambiguous=1, VS16 respected, emoji two cells.

// WidthPolicy describes how the target terminal measures ambiguous graphemes.
// All fields are advisory knobs for terminal quirks, never Unicode truth:
// changing them changes what lux draws and measures, in lockstep.
//
// The zero value fits modern terminals and changes nothing.
type WidthPolicy struct {
	// AmbiguousWidth is the cell width of East Asian Ambiguous codepoints
	// (Greek, Cyrillic, box drawing, unit signs, enclosed alphanumerics,
	// private-use planes). 1 is the Western default, 2 matches terminals
	// running a CJK locale (xterm in ja_JP.UTF-8, mlterm, older konsole).
	// Any value other than 2 behaves as 1. lux.WithWidthPolicy rejects
	// values outside {1, 2}.
	AmbiguousWidth int

	// VS16Blind marks terminals that ignore U+FE0F emoji presentation
	// selectors: "❤️" occupies one cell instead of two. The policy strips one
	// trailing VS16 from a cluster before measuring, so "❤" and "❤️" render
	// identically. VS15 text-presentation selectors are always respected and
	// never stripped.
	VS16Blind bool

	// NarrowEmoji marks terminals that render every emoji-presentation
	// grapheme in a single cell: "😀", "😀🏽" and "⚽" all advance one column.
	// Clusters carrying VS16 are treated as emoji regardless of the base
	// codepoint, so "❤️" narrows even though U+2764 defaults to text
	// presentation. CJK wide ideographs are never affected.
	NarrowEmoji bool
}

