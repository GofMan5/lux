// active reports whether p deviates from the default policy at all. The
// render hot path checks this once per cluster: an inactive policy keeps the
// overlay fast path byte-for-byte, with no table lookups.
func (p WidthPolicy) active() bool {
	return p.AmbiguousWidth == 2 || p.VS16Blind || p.NarrowEmoji
}

// terminalWidthOf measures one grapheme cluster under policy. VS16Blind
// strips one trailing U+FE0F first and re-measures the remainder through the
// full overlay-aware path (the cluster shrinks every strip, so the recursion
// terminates); the default-policy path stays exactly terminalWidth.
func terminalWidthOf(cluster string, policy WidthPolicy) int {
	if !policy.active() {
		return terminalWidth(cluster)
	}
	if policy.VS16Blind && strings.HasSuffix(cluster, "\uFE0F") {
		return terminalWidthOf(cluster[:len(cluster)-len("\uFE0F")], policy)
	}
	return policy.adjust(cluster, terminalWidth(cluster))
}

// adjust applies terminal quirks to the already measured width of cluster.
// Only width-1 clusters can be promoted by the ambiguous rule (zero-width
// combining clusters stay zero) and only width-2 clusters can be demoted by
// the emoji rule; the base rune decides both, VS16 presence counts as emoji
// presentation.
func (p WidthPolicy) adjust(cluster string, width int) int {
	if width == 1 && p.AmbiguousWidth == 2 {
		if base, _ := utf8.DecodeRuneInString(cluster); ambiguousRune(base) {
			return 2
		}
	}
	if width == 2 && p.NarrowEmoji {
		if base, _ := utf8.DecodeRuneInString(cluster); base == utf8.RuneError && !strings.HasPrefix(cluster, "\uFFFD") {
			// Undecodable input: fall through unchanged.
		} else if emojiPresentationRune(base) || strings.Contains(cluster, "\uFE0F") {
			return 1
		}
	}
	return width
}

func ambiguousRune(r rune) bool {
	return rangeContains(ambiguousRanges, r)
}

func emojiPresentationRune(r rune) bool {
	return rangeContains(emojiPresentationRanges, r)
}
